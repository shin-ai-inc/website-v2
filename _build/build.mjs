let css = "/* Generated by _build/build.mjs — edit sources in styles/, not this file. */\n";
css += read("styles/tokens.css") + "\n";
css += read("styles/base.css") + "\n";
for (const f of sectionFiles) {
  css += "\n/* sections/" + f + " */\n" + read(join("styles", "sections", f)) + "\n";
}
